/** The emoji whose names start with `typed`, up to `limit` */
export const emojiFor = (typed: string, limit = 6): { name: string; emoji: string }[] =>
  Object.entries(EMOJI)
    .filter(([name]) => name.startsWith(typed.toLowerCase()))
    .slice(0, limit)
    .map(([name, emoji]) => ({ name, emoji }));
